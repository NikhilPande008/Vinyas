"""Benchmark Tier-1B visual-gate models on mock-rig frames in upload mode (image decides).

Each frame is sent with NOMINAL telemetry features and no flags, which is exactly what the
custom-upload path does, so the vote measures what the model sees in the image alone.
Visual ground truth: SOLDER_BRIDGE, INSUFFICIENT_SOLDER, POROSITY_GAS_LOSS are visible defects;
everything else (nominal, flux glare, spatter, and every CNC frame, because the bearing is
inside the spindle) has no visible defect.

Decision rule (fixed before running): primary = highest visible-defect recall among models that
answered >= 75% of frames with a false-alarm rate <= 30%; ties go to the faster p50.

Usage:
    python scripts/benchmark_visual_gate.py gemma-4-26b-a4b-it,gemini-3.5-flash-lite,gemini-3.1-flash-lite
"""

from __future__ import annotations

import asyncio
from datetime import datetime, timezone
import json
from pathlib import Path
import statistics
import sys
import time

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from google import genai  # noqa: E402
from google.genai import types as genai_types  # noqa: E402

from backend.config import PROJECT_ROOT, get_settings  # noqa: E402
from backend.dsp.envelope import evaluate_t1a_signal_gate  # noqa: E402
from backend.mock_rig.dataset import LINE_DEFINITIONS, MANIFEST_PATH, SAMPLES_DIR, ensure_dataset  # noqa: E402
from backend.schemas import SensorTelemetry  # noqa: E402
from backend.services.model_router import build_t1b_prompt, parse_t1b_response  # noqa: E402

HEADER = (
    "Measured on simulated inputs generated by backend/mock_rig (organiser-approved, no hardware). "
    "Not field accuracy."
)
VISIBLE_DEFECTS = {"SOLDER_BRIDGE", "INSUFFICIENT_SOLDER", "POROSITY_GAS_LOSS"}
NOMINAL_TELEMETRY = {
    "PCB": SensorTelemetry(
        vibration_khz=0.35, vibration_rms_mms=0.7, temperature_c=242.0, line_speed_rpm=1200,
        reflow_ramp_c_per_s=2.0, reflow_peak_c=242.0, reflow_tal_s=65.0,
    ),
    "WELD": SensorTelemetry(
        vibration_khz=0.8, vibration_rms_mms=1.3, temperature_c=270.0, line_speed_rpm=1850,
        shielding_gas_lpm=17.0, arc_voltage_v=22.0, wire_feed_m_per_min=8.5,
    ),
    "CNC": SensorTelemetry(vibration_khz=0.09, vibration_rms_mms=0.9, temperature_c=41.0, line_speed_rpm=5400),
}
MAX_TRIES = 2
CONCURRENCY_PER_MODEL = 3
CALL_TIMEOUT_SEC = 20.0
RATE_LIMIT_BACKOFF_SEC = 30.0


def _pct(vals: list[int], q: float) -> int | None:
    s = sorted(vals)
    return s[min(len(s) - 1, int(len(s) * q))] if s else None


async def _ask(client, model: str, image: bytes, prompt: str) -> dict:
    cfg = genai_types.GenerateContentConfig(response_mime_type="application/json", temperature=0.1)
    last_err = ""
    for attempt in range(1, MAX_TRIES + 1):
        t0 = time.perf_counter()
        try:
            resp = await asyncio.wait_for(
                asyncio.to_thread(
                    client.models.generate_content,
                    model=model,
                    contents=[genai_types.Part.from_bytes(data=image, mime_type="image/png"), prompt],
                    config=cfg,
                ),
                timeout=CALL_TIMEOUT_SEC,
            )
            ms = int((time.perf_counter() - t0) * 1000)
            vote, conf, obs, _ = parse_t1b_response(resp.text or "")
            return {"vote": vote, "confidence": conf, "obs": obs[:1], "latency_ms": ms, "tries": attempt}
        except Exception as exc:  # noqa: BLE001 - recorded, then retried
            last_err = f"{type(exc).__name__}: {str(exc)[:60]}"
            # 429 on the free tier is per-minute throttling: wait out the window before retrying
            await asyncio.sleep(RATE_LIMIT_BACKOFF_SEC if "429" in last_err else 2.0 * attempt)
    return {"vote": None, "error": last_err, "tries": MAX_TRIES}


async def _run_model(client, model: str, samples: list[dict], concurrency: int = CONCURRENCY_PER_MODEL) -> list[dict]:
    sem = asyncio.Semaphore(concurrency)

    async def _one(s: dict) -> dict:
        async with sem:
            return await _run_frame(client, model, s)

    return list(await asyncio.gather(*(_one(s) for s in samples)))


async def _run_frame(client, model: str, s: dict) -> dict:
    line = s["line"]
    t1a = evaluate_t1a_signal_gate(line, NOMINAL_TELEMETRY[line], None)
    prompt = build_t1b_prompt(line, LINE_DEFINITIONS[line], t1a.features, [])
    image = (SAMPLES_DIR / s["sample_id"] / "frame.png").read_bytes()
    res = await _ask(client, model, image, prompt)
    res.update(
        sample_id=s["sample_id"],
        line=line,
        ground_truth=s["defect_type"],
        visible_defect=s["defect_type"] in VISIBLE_DEFECTS,
    )
    print(model, s["sample_id"], s["defect_type"], res.get("vote") or res.get("error"), flush=True)
    return res


def _summarise(model: str, rows: list[dict]) -> dict:
    answered = [r for r in rows if r["vote"]]
    pos = [r for r in answered if r["visible_defect"]]
    neg = [r for r in answered if not r["visible_defect"]]
    tp = sum(1 for r in pos if r["vote"] == "ANOMALY")
    fp = sum(1 for r in neg if r["vote"] == "ANOMALY")
    lats = [r["latency_ms"] for r in answered]
    return {
        "model": model,
        "frames": len(rows),
        "answered": len(answered),
        "answer_rate_pct": round(100.0 * len(answered) / max(1, len(rows)), 1),
        "visible_defects_answered": len(pos),
        "defects_caught": tp,
        "recall_pct": round(100.0 * tp / len(pos), 1) if pos else None,
        "no_defect_answered": len(neg),
        "false_alarms": fp,
        "false_alarm_pct": round(100.0 * fp / len(neg), 1) if neg else None,
        "p50_ms": _pct(lats, 0.5),
        "p95_ms": _pct(lats, 0.95),
        "mean_tries": round(statistics.mean(r["tries"] for r in rows), 2) if rows else None,
    }


def _choose(summaries: list[dict]) -> dict | None:
    eligible = [
        s for s in summaries
        if s["answer_rate_pct"] >= 75.0 and s["false_alarm_pct"] is not None and s["false_alarm_pct"] <= 30.0
        and s["recall_pct"] is not None
    ]
    if not eligible:
        return None
    return sorted(eligible, key=lambda s: (-s["recall_pct"], s["p50_ms"] or 10**9))[0]


async def _retry_failed(client, models: list[str], samples: list[dict]) -> list[list[dict]]:
    """Re-run only frames that got no vote in the previous run (e.g. throttled), then merge."""
    prev = json.loads((PROJECT_ROOT / "eval" / "visual_gate_benchmark.json").read_text(encoding="utf-8"))
    by_id = {s["sample_id"]: s for s in samples}
    async def _one_model(m: str) -> list[dict]:
        rows = prev["rows"][m]
        todo = [by_id[r["sample_id"]] for r in rows if not r.get("vote")]
        redo = {r["sample_id"]: r for r in await _run_model(client, m, todo, concurrency=1)}
        return [redo.get(r["sample_id"], r) if not r.get("vote") else r for r in rows]

    return list(await asyncio.gather(*(_one_model(m) for m in models)))


async def main() -> None:
    models = sys.argv[1].split(",")
    retry_failed = "--retry-failed" in sys.argv
    ensure_dataset()
    manifest = json.loads(MANIFEST_PATH.read_text(encoding="utf-8"))
    samples = [m for m in manifest if m["line"] in ("PCB", "WELD")]
    samples += [m for m in manifest if m["line"] == "CNC"][:6]
    client = genai.Client(api_key=get_settings().gemini_api_key)

    if retry_failed:
        results = await _retry_failed(client, models, samples)
    else:
        results = await asyncio.gather(*(_run_model(client, m, samples) for m in models))
    summaries = [_summarise(m, rows) for m, rows in zip(models, results)]
    chosen = _choose(summaries)

    out = {
        "header": HEADER,
        "timestamp_utc": datetime.now(timezone.utc).isoformat(),
        "decision_rule": "highest visible-defect recall with answer rate >= 75% and false-alarm rate <= 30%; tie -> faster p50",
        "summaries": summaries,
        "chosen": chosen["model"] if chosen else None,
        "rows": {m: rows for m, rows in zip(models, results)},
    }
    eval_dir = PROJECT_ROOT / "eval"
    (eval_dir / "visual_gate_benchmark.json").write_text(json.dumps(out, indent=2) + "\n", encoding="utf-8")

    md = [
        "# Tier-1B Visual Gate Benchmark (`eval/visual_gate_benchmark.md`)",
        "",
        f"> {HEADER}",
        "",
        f"Upload mode: each frame is sent with nominal telemetry and no flags, so the vote reflects the image alone. "
        f"{len(samples)} frames: 20 PCB, 20 WELD, 6 CNC (CNC frames never show a defect because the bearing is inside the spindle). "
        f"Prompt: `backend/services/model_router.py:build_t1b_prompt`. Up to {MAX_TRIES} tries per frame on API errors, {CALL_TIMEOUT_SEC:.0f} s per try.",
        "",
        f"- **Timestamp (UTC):** {out['timestamp_utc']}",
        f"- **Decision rule (fixed before the run):** {out['decision_rule']}",
        *(
            ["- **Retry pass:** frames with no vote in the first pass (free-tier 429/503) were re-run one at a time per model and merged."]
            if retry_failed
            else []
        ),
        f"- **Chosen primary:** `{out['chosen']}`" if out["chosen"] else "- **Chosen primary:** none met the rule",
        "",
        "| Model | Answered | Visible defects caught (recall) | False alarms on no-defect frames | p50 ms | p95 ms | Mean tries |",
        "| --- | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    for s in summaries:
        md.append(
            f"| `{s['model']}` | {s['answered']}/{s['frames']} | {s['defects_caught']}/{s['visible_defects_answered']} "
            f"({s['recall_pct']}%) | {s['false_alarms']}/{s['no_defect_answered']} ({s['false_alarm_pct']}%) | "
            f"{s['p50_ms']} | {s['p95_ms']} | {s['mean_tries']} |"
        )
    md += ["", "## Per-class votes (ANOMALY / answered)", "", "| Model | Class | ANOMALY | Answered |", "| --- | --- | ---: | ---: |"]
    for m, rows in zip(models, results):
        classes = sorted({(r["line"], r["ground_truth"]) for r in rows})
        for line, gt in classes:
            sub = [r for r in rows if r["line"] == line and r["ground_truth"] == gt and r["vote"]]
            md.append(f"| `{m}` | {line} {gt} | {sum(1 for r in sub if r['vote'] == 'ANOMALY')} | {len(sub)} |")
    (eval_dir / "visual_gate_benchmark.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print(json.dumps(summaries, indent=1))
    print("chosen:", out["chosen"])


if __name__ == "__main__":
    asyncio.run(main())
