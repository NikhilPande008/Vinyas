#!/usr/bin/env python3
"""Phase 6: End-to-end evaluation harness (`scripts/eval_pipeline.py`).

Runs manifest samples through `/api/inspect` (in-process ASGI or live HTTP URL)
and fetches ground truth via `GET /api/rig/reveal/{sample_id}?eval=1`.
Writes `eval/results.json` and `eval/RESULTS.md` (or `eval/live_run_<ts>.md`).
"""

from __future__ import annotations

import argparse
from datetime import datetime, timezone
import json
import statistics
import sys
import time
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import httpx

from backend.config import PROJECT_ROOT, get_settings
from backend.mock_rig.dataset import MANIFEST_PATH, ensure_dataset
from backend.services.metrics import compute_gate_token_accounting


HEADER_VERBATIM = (
    "Measured on simulated inputs generated by backend/mock_rig "
    "(organiser-approved, no hardware). Not field accuracy."
)


def _pct(vals: list[int], q: float) -> int:
    if not vals:
        return 0
    s = sorted(vals)
    idx = min(len(s) - 1, int(round(q * (len(s) - 1))))
    return int(s[idx])


def _select_samples(n: int) -> list[dict[str, Any]]:
    ensure_dataset()
    manifest = json.loads(MANIFEST_PATH.read_text(encoding="utf-8"))
    if n >= len(manifest):
        return manifest
    # Balanced slice across lines
    per_line = max(1, n // 3)
    out: list[dict[str, Any]] = []
    for line in ("PCB", "CNC", "WELD"):
        out.extend([m for m in manifest if m["line"] == line][:per_line])
    return out[:n]


def run_eval(target: str, url: str, n: int) -> dict[str, Any]:
    settings = get_settings()
    samples = _select_samples(n)
    eval_headers = {"X-Eval-Token": settings.eval_token}

    if target == "local":
        from fastapi.testclient import TestClient
        from backend.main import app, rate_limiter

        rate_limiter.reset()
        # Temporarily raise capacity for local 60-sample eval run
        orig_cap = rate_limiter.capacity
        rate_limiter.capacity = 500.0
        client: Any = TestClient(app)
        base = ""
    else:
        orig_cap = None
        client = httpx.Client(timeout=60.0)
        base = url.rstrip("/")

    records: list[dict[str, Any]] = []
    try:
        for idx, entry in enumerate(samples, start=1):
            sid = entry["sample_id"]
            t0 = time.perf_counter()
            r = client.post(f"{base}/api/inspect", json={"sample_id": sid})
            wall_ms = int((time.perf_counter() - t0) * 1000)
            if r.status_code != 200:
                records.append(
                    {
                        "sample_id": sid,
                        "line": entry["line"],
                        "error": f"HTTP {r.status_code}: {r.text[:120]}",
                        "wall_ms": wall_ms,
                    }
                )
                continue

            insp = r.json()
            rev = client.get(f"{base}/api/rig/reveal/{sid}?eval=1", headers=eval_headers)
            gt = rev.json() if rev.status_code == 200 else entry

            verdict = insp["tier1_triage"]["pass_status"]
            diag = insp.get("tier2_diagnosis")
            t2_defect = diag["defect_type"] if diag else None
            unverified_cnt = diag["unverified_value_count"] if diag else 0

            # Token accounting per stage
            t1_tok = 0
            t2_tok = 0
            fallback_stages: list[str] = []
            for p in insp.get("provenance", []):
                if p.get("producer") in ("FALLBACK_RULES", "FALLBACK_MODEL"):
                    fallback_stages.append(f"{p['stage']}:{p['producer']}")
                toks = sum((a.get("input_tokens") or 0) + (a.get("output_tokens") or 0) for a in p.get("attempts", []))
                if p["stage"] == "T1B_GATE":
                    t1_tok += toks
                elif p["stage"] == "T2_DIAGNOSIS":
                    t2_tok += toks

            rec = {
                "sample_id": sid,
                "line": gt["line"],
                "gt_is_defect": gt["is_defect"],
                "gt_defect_type": gt["defect_type"],
                "verdict": verdict,
                "t2_defect_type": t2_defect,
                "t2_agreed": (t2_defect == gt["defect_type"]) if (gt["is_defect"] and verdict == "ESCALATE") else None,
                "t1a_ms": insp["telemetry"]["t1a_ms"],
                "t1b_ms": insp["telemetry"]["t1b_ms"],
                "t1_ms": insp["telemetry"]["tier1_ms"],
                "retrieval_ms": insp["telemetry"]["retrieval_ms"],
                "t2_ms": insp["telemetry"]["tier2_ms"],
                "t3_ms": insp["telemetry"]["tier3_ms"],
                "total_ms": insp["telemetry"]["total_ms"],
                "wall_ms": wall_ms,
                "t1_tokens": t1_tok,
                "t2_tokens": t2_tok,
                "unverified_values": unverified_cnt,
                "fallback_stages": fallback_stages,
                "t1b_model": insp["telemetry"].get("tier1_model_used"),
                "t2_model": insp["telemetry"].get("tier2_model_used"),
            }
            records.append(rec)
            print(
                f"[{idx:02d}/{len(samples)}] {sid} gt={gt['defect_type']:18s} "
                f"gate={verdict:8s} t2={str(t2_defect):18s} {wall_ms}ms",
                flush=True,
            )
    finally:
        if target == "local" and orig_cap is not None:
            from backend.main import rate_limiter

            rate_limiter.capacity = orig_cap
            rate_limiter.reset()
        elif target != "local":
            client.close()

    valid = [r for r in records if "error" not in r]
    tp = sum(1 for r in valid if r["gt_is_defect"] and r["verdict"] == "ESCALATE")
    fn_list = [r["sample_id"] for r in valid if r["gt_is_defect"] and r["verdict"] == "HEALTHY"]
    fn = len(fn_list)
    fp_nom = sum(
        1 for r in valid if (not r["gt_is_defect"]) and r["gt_defect_type"] == "NOMINAL" and r["verdict"] == "ESCALATE"
    )
    tot_nom = sum(1 for r in valid if r["gt_defect_type"] == "NOMINAL")
    fp_hn = sum(
        1 for r in valid if (not r["gt_is_defect"]) and r["gt_defect_type"] != "NOMINAL" and r["verdict"] == "ESCALATE"
    )
    tot_hn = sum(1 for r in valid if (not r["gt_is_defect"]) and r["gt_defect_type"] != "NOMINAL")
    tn = sum(1 for r in valid if (not r["gt_is_defect"]) and r["verdict"] == "HEALTHY")
    fp = fp_nom + fp_hn

    recall = round(100.0 * tp / max(1, tp + fn), 1)
    fer_nom = round(100.0 * fp_nom / max(1, tot_nom), 1)
    fer_hn = round(100.0 * fp_hn / max(1, tot_hn), 1)

    t2_eval = [r for r in valid if r["t2_agreed"] is not None]
    t2_agree = sum(1 for r in t2_eval if r["t2_agreed"])
    t2_agree_pct = round(100.0 * t2_agree / max(1, len(t2_eval)), 1)

    t1a_lats = [r["t1a_ms"] for r in valid]
    t1b_lats = [r["t1b_ms"] for r in valid]
    t1_lats = [r["t1_ms"] for r in valid]
    t2_lats = [r["t2_ms"] for r in valid if r["verdict"] == "ESCALATE"]
    t3_lats = [r["t3_ms"] for r in valid if r["verdict"] == "ESCALATE"]
    tot_lats = [r["total_ms"] for r in valid]

    # Token accounting
    token_acc = compute_gate_token_accounting(
        n_parts=len(valid),
        t1_tokens_total=sum(r["t1_tokens"] for r in valid),
        n_escalated=sum(1 for r in valid if r["verdict"] == "ESCALATE"),
        t2_success_tokens=[r["t2_tokens"] for r in valid if r["t2_tokens"] > 0],
    )

    # Who actually answered each model stage (not just whether the stage produced output)
    t1b_answered: dict[str, int] = {}
    for r in valid:
        key = r.get("t1b_model") or "FALLBACK_RULES (gate unavailable)"
        t1b_answered[key] = t1b_answered.get(key, 0) + 1
    t2_by_model = [r for r in t2_eval if r.get("t2_model")]
    t2_by_rules = [r for r in t2_eval if not r.get("t2_model")]
    t2_agree_model = sum(1 for r in t2_by_model if r["t2_agreed"])
    t2_agree_rules = sum(1 for r in t2_by_rules if r["t2_agreed"])
    neg_by_model = [r for r in valid if not r["gt_is_defect"] and r.get("t2_model")]
    neg_model_clear = sum(1 for r in neg_by_model if r["t2_defect_type"] == "NO_DEFECT_FOUND")

    fallback_counts: dict[str, int] = {}
    for r in valid:
        for fb in r["fallback_stages"]:
            fallback_counts[fb] = fallback_counts.get(fb, 0) + 1

    unverified_total = sum(r["unverified_values"] for r in valid)
    batch_defect_rate = round(100.0 * (tp + fn) / max(1, len(valid)), 1)

    summary = {
        "header": HEADER_VERBATIM,
        "target": target,
        "url": url if target == "live" else "local-asgi",
        "timestamp_utc": datetime.now(timezone.utc).isoformat(),
        "n_requested": len(samples),
        "n_completed": len(valid),
        "n_errors": len(records) - len(valid),
        "confusion_matrix": {"tp": tp, "fn": fn, "fp": fp, "tn": tn},
        "defect_recall_pct": recall,
        "false_escalation_nominal_pct": fer_nom,
        "false_escalation_hard_negative_pct": fer_hn,
        "false_negatives": fn_list,
        "tier2_agreement": f"{t2_agree}/{len(t2_eval)} ({t2_agree_pct}%)",
        "tier2_agreement_by_model": f"{t2_agree_model}/{len(t2_by_model)}",
        "tier2_agreement_by_rules": f"{t2_agree_rules}/{len(t2_by_rules)}",
        "tier2_model_on_non_defects_no_defect_found": f"{neg_model_clear}/{len(neg_by_model)}",
        "t1b_answered_by": t1b_answered,
        "latencies_ms": {
            "t1a_p50": _pct(t1a_lats, 0.50),
            "t1a_p95": _pct(t1a_lats, 0.95),
            "t1b_p50": _pct(t1b_lats, 0.50),
            "t1b_p95": _pct(t1b_lats, 0.95),
            "t1_p50": _pct(t1_lats, 0.50),
            "t1_p95": _pct(t1_lats, 0.95),
            "t2_p50": _pct(t2_lats, 0.50),
            "t2_p95": _pct(t2_lats, 0.95),
            "t3_p50": _pct(t3_lats, 0.50),
            "t3_p95": _pct(t3_lats, 0.95),
            "total_p50": _pct(tot_lats, 0.50),
            "total_p95": _pct(tot_lats, 0.95),
        },
        "token_accounting": {"batch_defect_rate_pct": batch_defect_rate, **token_acc},
        "sop_guard_unverified_values_total": unverified_total,
        "fallback_counts": fallback_counts,
        "records": records,
    }
    return summary


def write_markdown(summary: dict[str, Any], out_path: Path) -> None:
    cm = summary["confusion_matrix"]
    lat = summary["latencies_ms"]
    tok = summary["token_accounting"]
    lines = [
        f"# Vinyas Pipeline Evaluation ({summary['target']})",
        "",
        f"> {summary['header']}",
        "",
        f"- **Timestamp (UTC):** {summary['timestamp_utc']}",
        f"- **Samples evaluated:** {summary['n_completed']} / {summary['n_requested']} (errors: {summary['n_errors']})",
        "",
        "## Gate Confusion Matrix (Tier-1: DSP + Gemma 4)",
        "",
        "| Ground Truth \\ Gate Verdict | ESCALATE | HEALTHY |",
        "| --- | ---: | ---: |",
        f"| **True Defect** | {cm['tp']} (TP) | {cm['fn']} (FN) |",
        f"| **Nominal / Hard Negative** | {cm['fp']} (FP) | {cm['tn']} (TN) |",
        "",
        f"- **True-defect recall:** `{summary['defect_recall_pct']}%` (`{cm['tp']}/{cm['tp'] + cm['fn']}`)",
        f"- **False-escalation rate (nominal):** `{summary['false_escalation_nominal_pct']}%`",
        f"- **False-escalation rate (hard negatives):** `{summary['false_escalation_hard_negative_pct']}%`",
        f"- **False negatives:** `{summary['false_negatives']}`",
        f"- **Tier-2 defect-type agreement (on escalated true defects):** `{summary['tier2_agreement']}` — answered by a Gemini model: `{summary['tier2_agreement_by_model']}`, by rule-based fallback: `{summary['tier2_agreement_by_rules']}`",
        f"- **Tier-2 model on nominal / hard-negative parts (returned NO_DEFECT_FOUND):** `{summary['tier2_model_on_non_defects_no_defect_found']}`",
        f"- **T1-B visual gate answered by:** `{json.dumps(summary['t1b_answered_by'])}`",
        f"- **SOP-guard unverified numeric values:** `{summary['sop_guard_unverified_values_total']}`",
        "",
        "## Per-Tier Measured Latencies (ms)",
        "",
        "| Stage | p50 (ms) | p95 (ms) |",
        "| --- | ---: | ---: |",
        f"| T1-A Deterministic DSP | {lat['t1a_p50']} | {lat['t1a_p95']} |",
        f"| T1-B Visual Gate | {lat['t1b_p50']} | {lat['t1b_p95']} |",
        f"| T1 Combined | {lat['t1_p50']} | {lat['t1_p95']} |",
        f"| T2 Root-Cause Diagnosis | {lat['t2_p50']} | {lat['t2_p95']} |",
        f"| T3 Deterministic Overlay | {lat['t3_p50']} | {lat['t3_p95']} |",
        f"| End-to-End Total | {lat['total_p50']} | {lat['total_p95']} |",
        "",
        "## Measured Token Accounting",
        "",
        f"- **Batch size (`N`):** `{summary['n_completed']}` (simulated batch defect rate: `{tok['batch_defect_rate_pct']}%`)",
        f"- **Escalated parts:** `{tok['n_escalated']}/{tok['n_parts']}` (Tier-2 calls succeeded: `{tok['t2_calls_succeeded']}`, failed: `{tok['t2_calls_failed']}`)",
        f"- **Measured T1 tokens (all parts):** `{tok['t1_tokens_total']:,}`; **mean measured T2 tokens per successful call:** `{tok['mean_t2_tokens']:,}`",
        f"- **Gated tokens (`T1 + escalations × mean T2`):** `{tok['gated_tokens']:,}`",
        f"- **Cloud-only tokens (`N × mean T2`):** `{tok['cloud_only_tokens']:,}`",
        f"- **Token effect of the gate in this run:** `{tok['saving_pct']}%` (negative means the gate cost more than it saved, which happens when it escalates most parts; failed Tier-2 calls are charged at the mean cost so outages never count as savings)",
        "",
        "## Fallbacks Recorded",
        f"```json\n{json.dumps(summary['fallback_counts'], indent=2)}\n```",
    ]
    out_path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--target", choices=["local", "live"], default="local")
    parser.add_argument("--url", default="https://vinyas-ai-65216244490.asia-south1.run.app")
    parser.add_argument("--n", type=int, default=60)
    args = parser.parse_args()

    summary = run_eval(args.target, args.url, args.n)
    eval_dir = PROJECT_ROOT / "eval"
    eval_dir.mkdir(parents=True, exist_ok=True)
    if args.target == "local":
        (eval_dir / "results.json").write_text(json.dumps(summary, indent=2), encoding="utf-8")
        write_markdown(summary, eval_dir / "RESULTS.md")
        print(f"Wrote {eval_dir / 'RESULTS.md'}")
    else:
        ts = datetime.now(timezone.utc).strftime("%Y%m%d_%H%M%S")
        (eval_dir / f"live_run_{ts}.json").write_text(json.dumps(summary, indent=2), encoding="utf-8")
        write_markdown(summary, eval_dir / f"live_run_{ts}.md")
        print(f"Wrote {eval_dir / f'live_run_{ts}.md'}")


if __name__ == "__main__":
    main()
