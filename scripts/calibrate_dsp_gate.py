"""Calibrate the deterministic Tier-1A DSP / process gate against the hidden manifest.

Runs `backend/dsp/envelope.py:evaluate_t1a_signal_gate` on every mock-rig sample with
no model calls, and writes `eval/dsp_gate_calibration.md` + `.json`.

Usage:
    python scripts/calibrate_dsp_gate.py
"""

from __future__ import annotations

from collections import Counter, defaultdict
from datetime import datetime, timezone
import json
from pathlib import Path
import sys
import time

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from backend.config import PROJECT_ROOT  # noqa: E402
from backend.dsp.envelope import evaluate_t1a_signal_gate  # noqa: E402
from backend.mock_rig.dataset import MANIFEST_PATH, ensure_dataset, load_sample_public  # noqa: E402
from backend.schemas import SensorTelemetry  # noqa: E402

HEADER = (
    "Measured on simulated inputs generated by backend/mock_rig (organiser-approved, no hardware). "
    "Not field accuracy."
)


def _pct(vals: list[float], q: float) -> float:
    s = sorted(vals)
    return round(s[min(len(s) - 1, int(len(s) * q))], 1) if s else 0.0


def main() -> None:
    ensure_dataset()
    manifest = {e["sample_id"]: e for e in json.loads(MANIFEST_PATH.read_text(encoding="utf-8"))}

    groups: dict[tuple[str, str, bool], Counter] = defaultdict(Counter)
    cnc_rows: list[dict] = []
    latencies: list[float] = []
    for sid, gt in sorted(manifest.items()):
        sample = load_sample_public(sid)
        telemetry = SensorTelemetry(**sample["telemetry"])
        wav = Path(sample["wav_path"]) if sample.get("wav_path") else None
        t0 = time.perf_counter()
        res = evaluate_t1a_signal_gate(sample["line"], telemetry, wav)
        latencies.append((time.perf_counter() - t0) * 1000.0)
        key = (sample["line"], gt["defect_type"], bool(gt["is_defect"]))
        groups[key]["n"] += 1
        groups[key]["flagged" if res.escalating_flags else "passed"] += 1
        if sample["line"] == "CNC":
            f = res.features
            cnc_rows.append(
                {
                    "sample_id": sid,
                    "ground_truth": gt["defect_type"],
                    "severity": gt["severity"],
                    "bpfo_snr_db": f.get("bpfo_snr_db"),
                    "bpfo_2x_snr_db": f.get("bpfo_2x_snr_db"),
                    "kurtosis": f.get("bandpass_kurtosis"),
                    "rms_mms": f.get("rms_velocity_mms"),
                    "iso_zone": f.get("iso_20816_3_zone"),
                    "escalating_flags": res.escalating_flags,
                    "info_flags": res.info_flags,
                }
            )

    defects = [c for (_, _, d), c in groups.items() if d]
    negatives = [c for (_, _, d), c in groups.items() if not d]
    summary = {
        "header": HEADER,
        "timestamp_utc": datetime.now(timezone.utc).isoformat(),
        "n_samples": len(manifest),
        "defects_flagged": sum(c["flagged"] for c in defects),
        "defects_total": sum(c["n"] for c in defects),
        "negatives_flagged": sum(c["flagged"] for c in negatives),
        "negatives_total": sum(c["n"] for c in negatives),
        "latency_ms_p50": _pct(latencies, 0.5),
        "latency_ms_p95": _pct(latencies, 0.95),
        "groups": [
            {"line": line, "ground_truth": dt, "is_defect": isdef, **dict(c)}
            for (line, dt, isdef), c in sorted(groups.items())
        ],
        "cnc_features": cnc_rows,
    }

    out_dir = PROJECT_ROOT / "eval"
    (out_dir / "dsp_gate_calibration.json").write_text(json.dumps(summary, indent=2) + "\n", encoding="utf-8")

    lines = [
        "# Tier-1A DSP Gate Calibration (`eval/dsp_gate_calibration.md`)",
        "",
        f"> {HEADER}",
        "",
        "Deterministic DSP / process-window gate alone (no model calls) on every mock-rig sample, compared with the hidden manifest. "
        "Generated by `python scripts/calibrate_dsp_gate.py`.",
        "",
        f"- **Timestamp (UTC):** {summary['timestamp_utc']}",
        f"- **True defects flagged:** `{summary['defects_flagged']}/{summary['defects_total']}`",
        f"- **Nominal + hard negatives flagged:** `{summary['negatives_flagged']}/{summary['negatives_total']}`",
        f"- **DSP latency per sample (local machine):** p50 `{summary['latency_ms_p50']} ms`, p95 `{summary['latency_ms_p95']} ms`",
        "",
        "| Line | Ground truth | Defect? | n | DSP flagged | DSP passed |",
        "| --- | --- | --- | ---: | ---: | ---: |",
    ]
    for g in summary["groups"]:
        lines.append(
            f"| {g['line']} | {g['ground_truth']} | {'yes' if g['is_defect'] else 'no'} | {g['n']} | "
            f"{g.get('flagged', 0)} | {g.get('passed', 0)} |"
        )
    lines += [
        "",
        "PCB defects with in-window reflow telemetry are expected to pass this gate (about 30% by design); "
        "the visual gate must catch them. Cosmetic hard negatives pass by design.",
        "",
        "## CNC Envelope Features",
        "",
        "Rule: `BEARING_PERIODIC_IMPACT` if BPFO SNR `≥ 14 dB` and 2×BPFO SNR `≥ 11 dB`; "
        "`TRANSIENT_IMPACT` (info only) if kurtosis `≥ 8` without BPFO periodicity; "
        "`VIBRATION_ZONE_C_OR_D` from ISO 20816-3 reference zones.",
        "",
        "| Sample | Ground truth | Severity | BPFO SNR dB | 2×BPFO SNR dB | Kurtosis | RMS mm/s | ISO zone | Escalating | Info |",
        "| --- | --- | --- | ---: | ---: | ---: | ---: | --- | --- | --- |",
    ]
    for r in cnc_rows:
        lines.append(
            f"| {r['sample_id']} | {r['ground_truth']} | {r['severity']} | {r['bpfo_snr_db']} | {r['bpfo_2x_snr_db']} | "
            f"{r['kurtosis']} | {r['rms_mms']} | {r['iso_zone']} | {', '.join(r['escalating_flags']) or '—'} | "
            f"{', '.join(r['info_flags']) or '—'} |"
        )
    lines += [
        "",
        "The separation is wide because the synthetic outer-race fault is strong; real spindle data will separate less cleanly.",
    ]
    (out_dir / "dsp_gate_calibration.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(
        f"defects flagged {summary['defects_flagged']}/{summary['defects_total']}, "
        f"negatives flagged {summary['negatives_flagged']}/{summary['negatives_total']}"
    )


if __name__ == "__main__":
    main()
